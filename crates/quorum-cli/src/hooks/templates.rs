//! Embedded shell templates for `quorum install --hook=<type>`.
//!
//! Both templates are POSIX sh (Bourne-compatible). The first 5 lines
//! contain the literal substring `# quorum-managed-hook` so the
//! idempotency scanner in [`super`] recognizes them on re-install.
//!
//! The templates handle `QUORUM_SKIP`, a missing `quorum` binary
//! (blocks under `fail-closed`, skipped with a note otherwise), and
//! `QUORUM_HOOK_POLICY` (`fail-open` default, `fail-closed`, `warn`)
//! per v1.0 §4.5.2 / §4.5.3. The actual review pipeline is invoked via
//! `quorum review --hook-mode=<type>`.

/// Marker scanned by [`super::is_managed`] over the first 5 lines.
pub const HOOK_MARKER: &str = "# quorum-managed-hook";

/// Pre-commit template. Reviews the staged diff (Phase 1A path) via
/// `DiffSource::StagedIndex`. Bypass message references `git commit`.
pub const PRE_COMMIT_TEMPLATE: &str = r##"#!/bin/sh
# quorum-managed-hook v4 (pre-commit)
# Generated by `quorum install --hook=pre-commit`. Modifying this file
# manually means subsequent `quorum install` invocations refuse to overwrite.
# Bypass for one commit: env QUORUM_SKIP=1 git commit ...

if [ "${QUORUM_SKIP:-0}" != "0" ]; then
    echo "quorum: skipped (QUORUM_SKIP set)" >&2
    exit 0
fi

if ! command -v quorum >/dev/null 2>&1; then
    if [ "${QUORUM_HOOK_POLICY:-fail-open}" = "fail-closed" ]; then
        echo "quorum: binary not on PATH; commit blocked (fail-closed). To bypass once: QUORUM_SKIP=1 git commit" >&2
        exit 1
    fi
    echo "quorum: binary not on PATH; skipping" >&2
    exit 0
fi

quorum review --hook-mode=pre-commit
HOOK_EXIT=$?

# Default fail-open: only exit 1 (high-severity findings) blocks.
# QUORUM_HOOK_POLICY=fail-closed blocks on any non-zero exit: tooling (2),
# auth (3), and a crash (a panic is 101, a signal death 128+N).
# QUORUM_HOOK_POLICY=warn never blocks regardless of exit code.
if [ "${QUORUM_HOOK_POLICY:-fail-open}" = "warn" ]; then
    exit 0
fi

if [ "$HOOK_EXIT" -eq 1 ]; then
    echo "" >&2
    echo "quorum: high-severity findings present; commit blocked." >&2
    echo "       run \`quorum review --tui\` to dismiss or \`quorum review\` for full output." >&2
    echo "       to bypass once: QUORUM_SKIP=1 git commit" >&2
    exit 1
fi

if [ "${QUORUM_HOOK_POLICY:-fail-open}" = "fail-closed" ] && [ "$HOOK_EXIT" -ne 0 ]; then
    echo "quorum: review failed (exit $HOOK_EXIT); commit blocked (fail-closed)." >&2
    echo "       to bypass once: QUORUM_SKIP=1 git commit" >&2
    exit 1
fi

exit 0
"##;

/// Pre-push template. Forwards Git's remote name and URL (`$1`, `$2`) and
/// its stdin ref tuples to `quorum review --hook-mode=pre-push`; the
/// binary parses each tuple and reviews what the destination lacks
/// (v0.6 spec AC 277a). Bypass message references `git push`.
pub const PRE_PUSH_TEMPLATE: &str = r##"#!/bin/sh
# quorum-managed-hook v4 (pre-push)
# Generated by `quorum install --hook=pre-push`. Modifying this file
# manually means subsequent `quorum install` invocations refuse to overwrite.
# Bypass for one push: env QUORUM_SKIP=1 git push ...
#
# Git passes the remote's name and URL as $1 and $2 (the URL twice when
# the push names no remote), and each ref being pushed on stdin as:
#     <local-ref> <local-sha> <remote-ref> <remote-sha>
# This hook forwards both to `quorum review --hook-mode=pre-push`, which
# works out per ref what the destination remote lacks and reviews that.

if [ "${QUORUM_SKIP:-0}" != "0" ]; then
    echo "quorum: skipped (QUORUM_SKIP set)" >&2
    exit 0
fi

if ! command -v quorum >/dev/null 2>&1; then
    if [ "${QUORUM_HOOK_POLICY:-fail-open}" = "fail-closed" ]; then
        echo "quorum: binary not on PATH; push blocked (fail-closed). To bypass once: QUORUM_SKIP=1 git push" >&2
        exit 1
    fi
    echo "quorum: binary not on PATH; skipping" >&2
    exit 0
fi

quorum review --hook-mode=pre-push --remote="$1" --url="$2"
HOOK_EXIT=$?

# Default fail-open: only exit 1 (high-severity findings) blocks.
# QUORUM_HOOK_POLICY=fail-closed blocks on any non-zero exit: tooling (2),
# auth (3), and a crash (a panic is 101, a signal death 128+N).
# QUORUM_HOOK_POLICY=warn never blocks regardless of exit code.
if [ "${QUORUM_HOOK_POLICY:-fail-open}" = "warn" ]; then
    exit 0
fi

if [ "$HOOK_EXIT" -eq 1 ]; then
    echo "" >&2
    echo "quorum: high-severity findings present; push blocked." >&2
    echo "       run \`quorum review --tui\` to dismiss or \`quorum review\` for full output." >&2
    echo "       to bypass once: QUORUM_SKIP=1 git push" >&2
    exit 1
fi

if [ "${QUORUM_HOOK_POLICY:-fail-open}" = "fail-closed" ] && [ "$HOOK_EXIT" -ne 0 ]; then
    echo "quorum: review failed (exit $HOOK_EXIT); push blocked (fail-closed)." >&2
    echo "       to bypass once: QUORUM_SKIP=1 git push" >&2
    exit 1
fi

exit 0
"##;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn marker_present_in_first_five_lines_of_both_templates() {
        for (name, body) in [
            ("pre-commit", PRE_COMMIT_TEMPLATE),
            ("pre-push", PRE_PUSH_TEMPLATE),
        ] {
            let first_five = body.lines().take(5).collect::<Vec<_>>().join("\n");
            assert!(
                first_five.contains(HOOK_MARKER),
                "{name} template must contain {HOOK_MARKER:?} in its first 5 lines"
            );
        }
    }

    #[test]
    fn templates_start_with_posix_shebang() {
        for (name, body) in [
            ("pre-commit", PRE_COMMIT_TEMPLATE),
            ("pre-push", PRE_PUSH_TEMPLATE),
        ] {
            assert!(
                body.starts_with("#!/bin/sh\n"),
                "{name} template must start with #!/bin/sh"
            );
        }
    }

    #[test]
    fn pre_commit_template_references_git_commit_bypass() {
        assert!(PRE_COMMIT_TEMPLATE.contains("QUORUM_SKIP=1 git commit"));
        assert!(PRE_COMMIT_TEMPLATE.contains("commit blocked"));
    }

    #[test]
    fn pre_push_template_references_git_push_bypass() {
        assert!(PRE_PUSH_TEMPLATE.contains("QUORUM_SKIP=1 git push"));
        assert!(PRE_PUSH_TEMPLATE.contains("push blocked"));
    }

    #[test]
    fn templates_invoke_correct_hook_mode() {
        assert!(PRE_COMMIT_TEMPLATE.contains("quorum review --hook-mode=pre-commit"));
        assert!(PRE_PUSH_TEMPLATE.contains("quorum review --hook-mode=pre-push"));
    }

    #[test]
    fn templates_honor_quorum_hook_policy() {
        for body in [PRE_COMMIT_TEMPLATE, PRE_PUSH_TEMPLATE] {
            assert!(body.contains("QUORUM_HOOK_POLICY"));
            assert!(body.contains("warn"));
            assert!(body.contains("fail-closed"));
            assert!(body.contains("fail-open"));
        }
    }

    #[test]
    fn templates_handle_quorum_skip_and_missing_binary() {
        for body in [PRE_COMMIT_TEMPLATE, PRE_PUSH_TEMPLATE] {
            assert!(body.contains("QUORUM_SKIP"));
            assert!(body.contains("command -v quorum"));
            assert!(body.contains("binary not on PATH"));
        }
    }

    /// Run `template` with `sh`, against a stub `quorum` first on `PATH`
    /// that exits `quorum_exit`, under `QUORUM_HOOK_POLICY=policy`.
    /// Returns the hook's own exit code.
    fn run_template(template: &str, policy: &str, quorum_exit: i32) -> i32 {
        let td = tempfile::TempDir::new().unwrap();
        let bin = td.path().join("bin");
        std::fs::create_dir_all(&bin).unwrap();
        let stub = bin.join("quorum");
        std::fs::write(&stub, format!("#!/bin/sh\nexit {quorum_exit}\n")).unwrap();
        let hook = td.path().join("hook");
        std::fs::write(&hook, template).unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            for p in [&stub, &hook] {
                std::fs::set_permissions(p, std::fs::Permissions::from_mode(0o755)).unwrap();
            }
        }
        let mut path = vec![bin];
        path.extend(std::env::split_paths(
            &std::env::var_os("PATH").unwrap_or_default(),
        ));
        let out = std::process::Command::new("sh")
            .arg(&hook)
            .env("PATH", std::env::join_paths(path).unwrap())
            .env("QUORUM_HOOK_POLICY", policy)
            .env_remove("QUORUM_SKIP")
            .stdin(std::process::Stdio::null())
            .output()
            .expect("`sh` must be on PATH to run the hook templates");
        let stderr = String::from_utf8_lossy(&out.stderr);
        assert!(
            !stderr.contains("binary not on PATH"),
            "the stub `quorum` was not found: {stderr}"
        );
        out.status.code().expect("hook exited without a code")
    }

    /// Fail-closed blocks on any non-zero exit: a panic (101) and a signal
    /// death (128 + 9) block like tooling and auth errors. Fail-open and
    /// warn still let both through.
    #[test]
    fn fail_closed_blocks_on_any_nonzero_exit_including_crashes() {
        let mut wrong = Vec::new();
        for (name, template) in [
            ("pre-commit", PRE_COMMIT_TEMPLATE),
            ("pre-push", PRE_PUSH_TEMPLATE),
        ] {
            for quorum_exit in [101, 137] {
                for (policy, want) in [("fail-closed", 1), ("fail-open", 0), ("warn", 0)] {
                    let got = run_template(template, policy, quorum_exit);
                    if got != want {
                        wrong.push(format!(
                            "{name}, {policy}, quorum exit {quorum_exit}: hook exit {got}, want {want}"
                        ));
                    }
                }
            }
        }
        assert!(wrong.is_empty(), "{}", wrong.join("\n"));
    }

    /// v4 is the template whose pre-push passes Git's remote name and URL
    /// to `quorum` (AC 277a). v3 made fail-closed also block when `quorum`
    /// is not on `PATH`; v2 blocked any non-zero exit; v1 let crashes
    /// through. The version on the marker line tells them apart.
    #[test]
    fn templates_carry_the_v4_marker() {
        for (name, body) in [
            ("pre-commit", PRE_COMMIT_TEMPLATE),
            ("pre-push", PRE_PUSH_TEMPLATE),
        ] {
            assert_eq!(
                body.lines().nth(1),
                Some(format!("{HOOK_MARKER} v4 ({name})").as_str())
            );
        }
    }

    /// AC 277a: the pre-push hook forwards `$1` (remote name) and `$2`
    /// (URL) as `--remote` and `--url`, intact, even when they hold
    /// spaces or start with `-`.
    #[test]
    // The spaces in the hook's arguments are the point of the test.
    #[allow(clippy::suspicious_command_arg_space)]
    fn pre_push_template_forwards_the_remote_name_and_url() {
        let td = tempfile::TempDir::new().unwrap();
        let bin = td.path().join("bin");
        std::fs::create_dir_all(&bin).unwrap();
        let args_file = td.path().join("args");
        let stub = bin.join("quorum");
        std::fs::write(
            &stub,
            format!(
                "#!/bin/sh\nfor a in \"$@\"; do printf '%s\\n' \"$a\"; done > '{}'\nexit 0\n",
                args_file.to_str().unwrap().replace('\\', "/")
            ),
        )
        .unwrap();
        let hook = td.path().join("hook");
        std::fs::write(&hook, PRE_PUSH_TEMPLATE).unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            for p in [&stub, &hook] {
                std::fs::set_permissions(p, std::fs::Permissions::from_mode(0o755)).unwrap();
            }
        }
        let mut path = vec![bin];
        path.extend(std::env::split_paths(
            &std::env::var_os("PATH").unwrap_or_default(),
        ));
        let out = std::process::Command::new("sh")
            .arg(&hook)
            .arg("-my remote")
            .arg("https://host.invalid/a b.git")
            .env("PATH", std::env::join_paths(path).unwrap())
            .env_remove("QUORUM_SKIP")
            .env_remove("QUORUM_HOOK_POLICY")
            .stdin(std::process::Stdio::null())
            .output()
            .unwrap();
        assert_eq!(out.status.code(), Some(0), "{out:?}");
        let got = std::fs::read_to_string(&args_file).unwrap();
        assert_eq!(
            got.lines().collect::<Vec<_>>(),
            [
                "review",
                "--hook-mode=pre-push",
                "--remote=-my remote",
                "--url=https://host.invalid/a b.git",
            ]
        );
    }

    /// The absolute path of `sh` on the test's own `PATH`, so the hook can
    /// run under a `PATH` that holds nothing else.
    fn sh_path() -> std::path::PathBuf {
        let names: &[&str] = if cfg!(windows) {
            &["sh.exe", "sh"]
        } else {
            &["sh"]
        };
        std::env::split_paths(&std::env::var_os("PATH").unwrap_or_default())
            .flat_map(|d| names.iter().map(move |n| d.join(n)))
            .find(|p| p.is_file())
            .expect("`sh` must be on PATH to run the hook templates")
    }

    /// With no `quorum` on `PATH`, fail-closed blocks and says why in one
    /// line; fail-open (also the default) and warn let it through with
    /// the skip note.
    #[test]
    fn a_missing_binary_blocks_only_under_fail_closed() {
        let mut wrong = Vec::new();
        for (name, template) in [
            ("pre-commit", PRE_COMMIT_TEMPLATE),
            ("pre-push", PRE_PUSH_TEMPLATE),
        ] {
            for (policy, want) in [
                (Some("fail-closed"), 1),
                (Some("fail-open"), 0),
                (Some("warn"), 0),
                (None, 0),
            ] {
                let td = tempfile::TempDir::new().unwrap();
                let empty = td.path().join("empty-path");
                std::fs::create_dir_all(&empty).unwrap();
                let hook = td.path().join("hook");
                std::fs::write(&hook, template).unwrap();
                let mut cmd = std::process::Command::new(sh_path());
                cmd.arg(&hook)
                    .env("PATH", &empty)
                    .env_remove("QUORUM_SKIP")
                    .stdin(std::process::Stdio::null());
                match policy {
                    Some(p) => cmd.env("QUORUM_HOOK_POLICY", p),
                    None => cmd.env_remove("QUORUM_HOOK_POLICY"),
                };
                let out = cmd.output().unwrap();
                let stderr = String::from_utf8_lossy(&out.stderr);
                let lines: Vec<&str> = stderr.lines().filter(|l| !l.is_empty()).collect();
                let said_why = lines.len() == 1
                    && lines[0].contains("binary not on PATH")
                    && (want == 0 || lines[0].contains("blocked"));
                if out.status.code() != Some(want) || !said_why {
                    wrong.push(format!(
                        "{name}, policy {policy:?}: exit {:?}, want {want}; stderr {lines:?}",
                        out.status.code()
                    ));
                }
            }
        }
        assert!(wrong.is_empty(), "{}", wrong.join("\n"));
    }
}
